//! The typed boundary between the React UI and the Rust shell.
//!
//! Every command, event and transfer type that crosses the boundary is registered in
//! [`bindings_builder`]. `tauri-specta` turns that one registry into the invoke handler, the
//! event wiring and the generated TypeScript bindings, so the two sides cannot drift apart:
//! `pnpm check` regenerates the bindings and fails when the committed file differs.

use std::path::Path;

use serde::{Deserialize, Serialize};
use specta::Type;
use specta_typescript::Typescript;
use tauri_specta::{Builder, Event, collect_commands, collect_events};
use volt_core::PortError;

use crate::AppInfo;

/// Header written at the top of the generated bindings file.
const BINDINGS_HEADER: &str = "// This file is generated by tauri-specta from the Rust shell (apps/desktop/src-tauri).\n\
// Do not edit it by hand: change the Rust command or type, then run `pnpm bindings`.\n\
// The generator emits an import it does not always use, which our strict compiler options reject.\n\
// @ts-nocheck";

/// The one error type every command returns.
///
/// It reaches the UI as a discriminated value, `{ kind: "notFound", message: "..." }`, so the
/// frontend switches on `kind` instead of parsing a string. The variants mirror
/// [`volt_core::PortError`] so the UI can tell the user what kind of failure happened.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, Type)]
#[serde(tag = "kind", rename_all = "camelCase")]
pub enum IpcError {
    /// The addressed object (value, service, file, entry) does not exist.
    NotFound {
        /// Human-readable detail.
        message: String,
    },
    /// The request needs rights the app does not have (for example administrator rights).
    AccessDenied {
        /// Human-readable detail.
        message: String,
    },
    /// This platform or adapter cannot do what was asked.
    Unsupported {
        /// Human-readable detail.
        message: String,
    },
    /// The request itself is malformed.
    InvalidInput {
        /// Human-readable detail.
        message: String,
    },
    /// Any other failure.
    Other {
        /// Human-readable detail.
        message: String,
    },
}

impl IpcError {
    /// The human-readable detail, whatever the kind.
    #[must_use]
    pub fn message(&self) -> &str {
        match self {
            Self::NotFound { message }
            | Self::AccessDenied { message }
            | Self::Unsupported { message }
            | Self::InvalidInput { message }
            | Self::Other { message } => message,
        }
    }
}

impl From<PortError> for IpcError {
    fn from(error: PortError) -> Self {
        match error {
            PortError::NotFound(message) => Self::NotFound { message },
            PortError::AccessDenied(message) => Self::AccessDenied { message },
            PortError::Unsupported(message) => Self::Unsupported { message },
            PortError::InvalidInput(message) => Self::InvalidInput { message },
            // `PortError` is non-exhaustive: a variant added later degrades to `Other` with its
            // own message until the UI learns about it.
            other => Self::Other {
                message: other.to_string(),
            },
        }
    }
}

/// Event emitted once the page has loaded, carrying the identity of the running app.
///
/// The sample typed event: generated as `events.appReady` on the TypeScript side.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, Type, Event)]
pub struct AppReady(pub AppInfo);

/// Registers every command, event and type of the boundary in one place.
#[must_use]
pub fn bindings_builder() -> Builder<tauri::Wry> {
    Builder::<tauri::Wry>::new()
        .commands(collect_commands![
            crate::app_info,
            crate::autostart::autostart_enabled,
            crate::autostart::set_autostart,
        ])
        .events(collect_events![AppReady, crate::TrayBoostRequested])
        .typ::<IpcError>()
}

/// Writes the TypeScript bindings to `path`.
///
/// # Errors
/// Returns the exporter's error when a type cannot be represented in TypeScript (for example a
/// 64-bit integer) or the file cannot be written.
pub fn export_bindings(path: &Path) -> Result<(), specta_typescript::ExportError> {
    bindings_builder().export(Typescript::default().header(BINDINGS_HEADER), path)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn port_errors_map_to_the_matching_kind_and_keep_the_message() {
        let cases = [
            (
                PortError::NotFound("key".into()),
                IpcError::NotFound {
                    message: "key".into(),
                },
            ),
            (
                PortError::AccessDenied("hklm".into()),
                IpcError::AccessDenied {
                    message: "hklm".into(),
                },
            ),
            (
                PortError::Unsupported("linux".into()),
                IpcError::Unsupported {
                    message: "linux".into(),
                },
            ),
            (
                PortError::InvalidInput("path".into()),
                IpcError::InvalidInput {
                    message: "path".into(),
                },
            ),
            (
                PortError::Other("boom".into()),
                IpcError::Other {
                    message: "boom".into(),
                },
            ),
        ];
        for (port, expected) in cases {
            let mapped = IpcError::from(port);
            assert_eq!(mapped, expected);
            assert_eq!(mapped.message(), expected.message());
        }
    }

    #[test]
    fn ipc_errors_serialize_as_a_value_tagged_by_kind() {
        let json = serde_json::to_value(IpcError::from(PortError::NotFound("run key".into())))
            .unwrap_or_default();
        assert_eq!(
            json,
            serde_json::json!({ "kind": "notFound", "message": "run key" })
        );
    }
}
