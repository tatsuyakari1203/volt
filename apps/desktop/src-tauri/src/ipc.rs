//! The typed boundary between the React UI and the Rust shell.
//!
//! Every command, event and transfer type that crosses the boundary is registered in
//! [`bindings_builder`]. `tauri-specta` turns that one registry into the invoke handler, the
//! event wiring and the generated TypeScript bindings, so the two sides cannot drift apart:
//! `pnpm check` regenerates the bindings and fails when the committed file differs.

use std::path::Path;

use serde::{Deserialize, Serialize};
use specta::Type;
use specta_typescript::Typescript;
use tauri_specta::{Builder, Event, collect_commands, collect_events};
use volt_core::{ExecError, PlanError, PortError, RevertError, StartupError, TweakError};
use volt_store::StoreError;

use crate::AppInfo;

/// Header written at the top of the generated bindings file.
const BINDINGS_HEADER: &str = "// This file is generated by tauri-specta from the Rust shell (apps/desktop/src-tauri).\n\
// Do not edit it by hand: change the Rust command or type, then run `pnpm bindings`.\n\
// The generator emits an import it does not always use, which our strict compiler options reject.\n\
// @ts-nocheck";

/// The one error type every command returns.
///
/// It reaches the UI as a discriminated value, `{ kind: "notFound", message: "..." }`, so the
/// frontend switches on `kind` instead of parsing a string. The variants mirror
/// [`volt_core::PortError`] so the UI can tell the user what kind of failure happened.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, Type)]
#[serde(tag = "kind", rename_all = "camelCase")]
pub enum IpcError {
    /// The addressed object (value, service, file, entry) does not exist.
    NotFound {
        /// Human-readable detail.
        message: String,
    },
    /// The request needs rights the app does not have (for example administrator rights).
    AccessDenied {
        /// Human-readable detail.
        message: String,
    },
    /// This platform or adapter cannot do what was asked.
    Unsupported {
        /// Human-readable detail.
        message: String,
    },
    /// The request itself is malformed.
    InvalidInput {
        /// Human-readable detail.
        message: String,
    },
    /// Any other failure.
    Other {
        /// Human-readable detail.
        message: String,
    },
}

impl IpcError {
    /// The human-readable detail, whatever the kind.
    #[must_use]
    pub fn message(&self) -> &str {
        match self {
            Self::NotFound { message }
            | Self::AccessDenied { message }
            | Self::Unsupported { message }
            | Self::InvalidInput { message }
            | Self::Other { message } => message,
        }
    }
}

impl From<PortError> for IpcError {
    fn from(error: PortError) -> Self {
        match error {
            PortError::NotFound(message) => Self::NotFound { message },
            PortError::AccessDenied(message) => Self::AccessDenied { message },
            PortError::Unsupported(message) => Self::Unsupported { message },
            PortError::InvalidInput(message) => Self::InvalidInput { message },
            // `PortError` is non-exhaustive: a variant added later degrades to `Other` with its
            // own message until the UI learns about it.
            other => Self::Other {
                message: other.to_string(),
            },
        }
    }
}

/// The error of a port, with the kind the UI switches on and the message of the whole failure.
fn kinded(port: &PortError, message: String) -> IpcError {
    match port {
        PortError::NotFound(_) => IpcError::NotFound { message },
        PortError::AccessDenied(_) => IpcError::AccessDenied { message },
        PortError::Unsupported(_) => IpcError::Unsupported { message },
        PortError::InvalidInput(_) => IpcError::InvalidInput { message },
        // `PortError` is non-exhaustive: a variant added later degrades to `Other`.
        _ => IpcError::Other { message },
    }
}

impl From<TweakError> for IpcError {
    /// Keeps the kind of the underlying port failure when there is one, so the UI can tell
    /// "access denied" from "not found"; the message is the whole error, naming the tweak.
    fn from(error: TweakError) -> Self {
        let message = error.to_string();
        match &error {
            TweakError::UnknownTweak(_) | TweakError::NothingToRevert(_) => {
                Self::NotFound { message }
            }
            TweakError::NeedsAdministrator(_) => Self::AccessDenied { message },
            TweakError::Detect { error: port, .. }
            | TweakError::Journal { error: port, .. }
            | TweakError::Plan {
                error: PlanError::Detect { error: port, .. },
                ..
            }
            | TweakError::Exec {
                error:
                    ExecError::Detect(port)
                    | ExecError::Journal(port)
                    | ExecError::MarkApplied(port)
                    | ExecError::Apply { error: port, .. },
                ..
            }
            | TweakError::Revert {
                error:
                    RevertError::Journal(port)
                    | RevertError::Port(port)
                    | RevertError::MarkReverted(port),
                ..
            } => kinded(port, message),
            TweakError::Revert {
                error: RevertError::EntryNotFound(_),
                ..
            } => Self::NotFound { message },
            TweakError::Revert {
                error: RevertError::NotRevertible(_),
                ..
            } => Self::InvalidInput { message },
            // Both enums are non-exhaustive: anything new degrades to `Other`.
            _ => Self::Other { message },
        }
    }
}

impl From<StartupError> for IpcError {
    /// Machine-wide entries need administrator rights, which is `accessDenied` with a message the
    /// UI can show as it is; a failed change keeps the kind of the port failure under it. The
    /// messages are built from the core's redacted reasons, not from port messages.
    fn from(error: StartupError) -> Self {
        match &error {
            StartupError::InvalidId(_) => Self::InvalidInput {
                message: error.to_string(),
            },
            StartupError::NotFound(_) => Self::NotFound {
                message: error.to_string(),
            },
            StartupError::NeedsAdministrator { name } => Self::AccessDenied {
                message: format!("Changing \"{name}\" needs administrator rights."),
            },
            StartupError::Read(port) => kinded(
                port,
                format!(
                    "Volt could not read the startup entry ({}).",
                    volt_core::activity::error_class(port)
                ),
            ),
            StartupError::Change(exec) => {
                let message = format!(
                    "The startup entry could not be changed: {}.",
                    volt_core::activity::exec_reason(exec)
                );
                match exec {
                    ExecError::Detect(port)
                    | ExecError::Journal(port)
                    | ExecError::MarkApplied(port)
                    | ExecError::Apply { error: port, .. } => kinded(port, message),
                    // `ExecError` is non-exhaustive: anything new degrades to `Other`.
                    _ => Self::Other { message },
                }
            }
            // `StartupError` is non-exhaustive: anything new degrades to `Other`.
            _ => Self::Other {
                message: error.to_string(),
            },
        }
    }
}

impl From<StoreError> for IpcError {
    /// Opening the database failed. The UI can do nothing about the kind, so it is `Other`.
    fn from(error: StoreError) -> Self {
        Self::Other {
            message: error.to_string(),
        }
    }
}

/// Event emitted once the page has loaded, carrying the identity of the running app.
///
/// The sample typed event: generated as `events.appReady` on the TypeScript side.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, Type, Event)]
pub struct AppReady(pub AppInfo);

/// Registers every command, event and type of the boundary in one place.
#[must_use]
pub fn bindings_builder() -> Builder<tauri::Wry> {
    Builder::<tauri::Wry>::new()
        .commands(collect_commands![
            crate::app_info,
            crate::autostart::autostart_enabled,
            crate::autostart::set_autostart,
            crate::commands::list_tweaks,
            crate::commands::apply_tweak,
            crate::commands::revert_tweak,
            crate::commands::list_activity,
            crate::metrics::latest_metrics,
            crate::health::health_report,
            crate::commands::undo_entry,
            crate::commands::undo_batch,
            crate::commands::preview_undo_batch,
            crate::commands::export_activity,
            crate::commands::export_activity_text,
            crate::commands::list_startup_entries,
            crate::commands::set_startup_entry_enabled,
        ])
        .events(collect_events![
            AppReady,
            crate::TrayBoostRequested,
            crate::MetricsUpdated,
        ])
        .typ::<IpcError>()
}

/// Writes the TypeScript bindings to `path`.
///
/// # Errors
/// Returns the exporter's error when a type cannot be represented in TypeScript (for example a
/// 64-bit integer) or the file cannot be written.
pub fn export_bindings(path: &Path) -> Result<(), specta_typescript::ExportError> {
    bindings_builder().export(Typescript::default().header(BINDINGS_HEADER), path)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn port_errors_map_to_the_matching_kind_and_keep_the_message() {
        let cases = [
            (
                PortError::NotFound("key".into()),
                IpcError::NotFound {
                    message: "key".into(),
                },
            ),
            (
                PortError::AccessDenied("hklm".into()),
                IpcError::AccessDenied {
                    message: "hklm".into(),
                },
            ),
            (
                PortError::Unsupported("linux".into()),
                IpcError::Unsupported {
                    message: "linux".into(),
                },
            ),
            (
                PortError::InvalidInput("path".into()),
                IpcError::InvalidInput {
                    message: "path".into(),
                },
            ),
            (
                PortError::Other("boom".into()),
                IpcError::Other {
                    message: "boom".into(),
                },
            ),
        ];
        for (port, expected) in cases {
            let mapped = IpcError::from(port);
            assert_eq!(mapped, expected);
            assert_eq!(mapped.message(), expected.message());
        }
    }

    #[test]
    fn ipc_errors_serialize_as_a_value_tagged_by_kind() {
        let json = serde_json::to_value(IpcError::from(PortError::NotFound("run key".into())))
            .unwrap_or_default();
        assert_eq!(
            json,
            serde_json::json!({ "kind": "notFound", "message": "run key" })
        );
    }

    #[test]
    fn tweak_errors_keep_the_kind_of_the_port_failure_under_them() {
        let detect = TweakError::Detect {
            tweak: "x".into(),
            step: 0,
            error: PortError::AccessDenied("hklm".into()),
        };
        assert!(matches!(
            IpcError::from(detect),
            IpcError::AccessDenied { message } if message.contains("tweak `x`")
        ));
        let exec = TweakError::Exec {
            tweak: "x".into(),
            error: ExecError::Journal(PortError::Other("disk full".into())),
        };
        assert!(matches!(IpcError::from(exec), IpcError::Other { .. }));
        let unreadable = TweakError::Plan {
            tweak: "x".into(),
            error: PlanError::Detect {
                index: 0,
                error: PortError::Unsupported("commands".into()),
            },
        };
        assert!(matches!(
            IpcError::from(unreadable),
            IpcError::Unsupported { .. }
        ));
    }

    #[test]
    fn unknown_tweaks_and_nothing_to_revert_are_not_found() {
        assert!(matches!(
            IpcError::from(TweakError::UnknownTweak("nope".into())),
            IpcError::NotFound { .. }
        ));
        assert!(matches!(
            IpcError::from(TweakError::NothingToRevert("x".into())),
            IpcError::NotFound { .. }
        ));
    }

    #[test]
    fn a_tweak_that_needs_administrator_rights_is_access_denied() {
        assert!(matches!(
            IpcError::from(TweakError::NeedsAdministrator("x".into())),
            IpcError::AccessDenied { .. }
        ));
    }

    #[test]
    fn revert_errors_map_by_what_went_wrong() {
        let revert = |error| {
            IpcError::from(TweakError::Revert {
                tweak: "x".into(),
                error,
            })
        };
        assert!(matches!(
            revert(RevertError::Port(PortError::AccessDenied("k".into()))),
            IpcError::AccessDenied { .. }
        ));
        assert!(matches!(
            revert(RevertError::EntryNotFound(volt_core::EntryId(3))),
            IpcError::NotFound { .. }
        ));
        assert!(matches!(
            revert(RevertError::NotRevertible(volt_core::EntryState::Reverted)),
            IpcError::InvalidInput { .. }
        ));
    }

    #[test]
    fn startup_errors_keep_their_kind_and_say_administrator_rights_in_words() {
        let admin = IpcError::from(StartupError::NeedsAdministrator {
            name: "Vendor Updater".into(),
        });
        assert_eq!(
            admin,
            IpcError::AccessDenied {
                message: "Changing \"Vendor Updater\" needs administrator rights.".into()
            }
        );
        assert!(matches!(
            IpcError::from(StartupError::NotFound("x".into())),
            IpcError::NotFound { .. }
        ));
        assert!(matches!(
            IpcError::from(StartupError::InvalidId("x".into())),
            IpcError::InvalidInput { .. }
        ));
        // A failed change keeps the kind of the port failure and never carries its message.
        let failed = IpcError::from(StartupError::Change(ExecError::Apply {
            error: PortError::AccessDenied("secret detail".into()),
            journal: None,
        }));
        assert!(
            matches!(&failed, IpcError::AccessDenied { message } if !message.contains("secret"))
        );
        let unreadable =
            IpcError::from(StartupError::Read(PortError::Other("secret detail".into())));
        assert!(matches!(&unreadable, IpcError::Other { message } if !message.contains("secret")));
    }

    #[test]
    fn store_errors_reach_the_ui_as_other_with_their_message() {
        let error = StoreError::SchemaTooNew {
            found: 9,
            supported: 3,
        };
        let text = error.to_string();
        assert_eq!(IpcError::from(error), IpcError::Other { message: text });
    }
}
