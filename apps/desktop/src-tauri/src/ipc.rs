//! The typed boundary between the React UI and the Rust shell.
//!
//! Every command, event and transfer type that crosses the boundary is registered in
//! [`bindings_builder`]. `tauri-specta` turns that one registry into the invoke handler, the
//! event wiring and the generated TypeScript bindings, so the two sides cannot drift apart:
//! `pnpm check` regenerates the bindings and fails when the committed file differs.

use std::path::Path;

use serde::{Deserialize, Serialize};
use specta::Type;
use specta_typescript::Typescript;
use tauri_specta::{Builder, Event, collect_commands, collect_events};
use volt_core::activity::{error_class_phrase, exec_phrase, revert_phrase};
use volt_core::{ExecError, Phrase, PlanError, PortError, RevertError, StartupError, TweakError};
use volt_store::StoreError;

use crate::AppInfo;
use crate::phrase::PhraseView;

/// Header written at the top of the generated bindings file.
const BINDINGS_HEADER: &str = "// This file is generated by tauri-specta from the Rust shell (apps/desktop/src-tauri).\n\
// Do not edit it by hand: change the Rust command or type, then run `pnpm bindings`.\n\
// The generator emits an import it does not always use, which our strict compiler options reject.\n\
// @ts-nocheck";

/// The one error type every command returns.
///
/// It reaches the UI as a discriminated value, `{ kind: "notFound", message: "..." }`, so the
/// frontend switches on `kind` instead of parsing a string. The variants mirror
/// [`volt_core::PortError`] so the UI can tell the user what kind of failure happened.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, Type)]
#[serde(tag = "kind", rename_all = "camelCase")]
pub enum IpcError {
    /// The addressed object (value, service, file, entry) does not exist.
    NotFound {
        /// Human-readable detail, in English.
        message: String,
        /// `message` as a code and parameters, when the shell built the sentence.
        #[serde(default, skip_serializing_if = "Option::is_none")]
        phrase: Option<PhraseView>,
    },
    /// The request needs rights the app does not have (for example administrator rights).
    AccessDenied {
        /// Human-readable detail, in English.
        message: String,
        /// `message` as a code and parameters, when the shell built the sentence.
        #[serde(default, skip_serializing_if = "Option::is_none")]
        phrase: Option<PhraseView>,
    },
    /// This platform or adapter cannot do what was asked.
    Unsupported {
        /// Human-readable detail, in English.
        message: String,
        /// `message` as a code and parameters, when the shell built the sentence.
        #[serde(default, skip_serializing_if = "Option::is_none")]
        phrase: Option<PhraseView>,
    },
    /// The request itself is malformed.
    InvalidInput {
        /// Human-readable detail, in English.
        message: String,
        /// `message` as a code and parameters, when the shell built the sentence.
        #[serde(default, skip_serializing_if = "Option::is_none")]
        phrase: Option<PhraseView>,
    },
    /// A command did not finish in time and was stopped.
    TimedOut {
        /// Human-readable detail, in English.
        message: String,
        /// `message` as a code and parameters, when the shell built the sentence.
        #[serde(default, skip_serializing_if = "Option::is_none")]
        phrase: Option<PhraseView>,
    },
    /// Any other failure.
    Other {
        /// Human-readable detail, in English.
        message: String,
        /// `message` as a code and parameters, when the shell built the sentence.
        #[serde(default, skip_serializing_if = "Option::is_none")]
        phrase: Option<PhraseView>,
    },
}

/// The kind of a failure, without its sentence.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ErrorClass {
    /// The addressed object does not exist.
    NotFound,
    /// The request needs rights the app does not have.
    AccessDenied,
    /// This platform or adapter cannot do what was asked.
    Unsupported,
    /// The request itself is malformed.
    InvalidInput,
    /// A command did not finish in time.
    TimedOut,
    /// Any other failure.
    Other,
}

impl IpcError {
    /// The human-readable detail (English), whatever the kind.
    #[must_use]
    pub fn message(&self) -> &str {
        match self {
            Self::NotFound { message, .. }
            | Self::AccessDenied { message, .. }
            | Self::Unsupported { message, .. }
            | Self::InvalidInput { message, .. }
            | Self::TimedOut { message, .. }
            | Self::Other { message, .. } => message,
        }
    }

    /// The sentence as a code and parameters, when the shell described the failure with one.
    #[must_use]
    pub fn phrase(&self) -> Option<&PhraseView> {
        match self {
            Self::NotFound { phrase, .. }
            | Self::AccessDenied { phrase, .. }
            | Self::Unsupported { phrase, .. }
            | Self::InvalidInput { phrase, .. }
            | Self::TimedOut { phrase, .. }
            | Self::Other { phrase, .. } => phrase.as_ref(),
        }
    }

    /// The kind of failure, whatever the variant.
    #[must_use]
    pub fn class(&self) -> ErrorClass {
        match self {
            Self::NotFound { .. } => ErrorClass::NotFound,
            Self::AccessDenied { .. } => ErrorClass::AccessDenied,
            Self::Unsupported { .. } => ErrorClass::Unsupported,
            Self::InvalidInput { .. } => ErrorClass::InvalidInput,
            Self::TimedOut { .. } => ErrorClass::TimedOut,
            Self::Other { .. } => ErrorClass::Other,
        }
    }

    /// A failure of `class` described by `phrase`.
    #[must_use]
    pub fn coded(class: ErrorClass, phrase: &Phrase) -> Self {
        let message = phrase.english();
        let phrase = Some(PhraseView::from(phrase));
        match class {
            ErrorClass::NotFound => Self::NotFound { message, phrase },
            ErrorClass::AccessDenied => Self::AccessDenied { message, phrase },
            ErrorClass::Unsupported => Self::Unsupported { message, phrase },
            ErrorClass::InvalidInput => Self::InvalidInput { message, phrase },
            ErrorClass::TimedOut => Self::TimedOut { message, phrase },
            ErrorClass::Other => Self::Other { message, phrase },
        }
    }

    /// [`ErrorClass::NotFound`] described by `phrase`.
    #[must_use]
    pub fn not_found(phrase: &Phrase) -> Self {
        Self::coded(ErrorClass::NotFound, phrase)
    }

    /// [`ErrorClass::AccessDenied`] described by `phrase`.
    #[must_use]
    pub fn access_denied(phrase: &Phrase) -> Self {
        Self::coded(ErrorClass::AccessDenied, phrase)
    }

    /// [`ErrorClass::Unsupported`] described by `phrase`.
    #[must_use]
    pub fn unsupported(phrase: &Phrase) -> Self {
        Self::coded(ErrorClass::Unsupported, phrase)
    }

    /// [`ErrorClass::InvalidInput`] described by `phrase`.
    #[must_use]
    pub fn invalid(phrase: &Phrase) -> Self {
        Self::coded(ErrorClass::InvalidInput, phrase)
    }

    /// [`ErrorClass::Other`] described by `phrase`.
    #[must_use]
    pub fn other(phrase: &Phrase) -> Self {
        Self::coded(ErrorClass::Other, phrase)
    }

    /// A failure of `class` with a message only (a detail from outside the shell: an adapter, the
    /// operating system).
    pub(crate) fn plain(class: ErrorClass, message: String) -> Self {
        let phrase = None;
        match class {
            ErrorClass::NotFound => Self::NotFound { message, phrase },
            ErrorClass::AccessDenied => Self::AccessDenied { message, phrase },
            ErrorClass::Unsupported => Self::Unsupported { message, phrase },
            ErrorClass::InvalidInput => Self::InvalidInput { message, phrase },
            ErrorClass::TimedOut => Self::TimedOut { message, phrase },
            ErrorClass::Other => Self::Other { message, phrase },
        }
    }
}

impl From<PortError> for IpcError {
    fn from(error: PortError) -> Self {
        match error {
            PortError::NotFound(message) => Self::plain(ErrorClass::NotFound, message),
            PortError::AccessDenied(message) => Self::plain(ErrorClass::AccessDenied, message),
            PortError::Unsupported(message) => Self::plain(ErrorClass::Unsupported, message),
            PortError::InvalidInput(message) => Self::plain(ErrorClass::InvalidInput, message),
            PortError::TimedOut(message) => Self::plain(ErrorClass::TimedOut, message),
            // `PortError` is non-exhaustive: a variant added later degrades to `Other` with its
            // own message until the UI learns about it.
            other => Self::plain(ErrorClass::Other, other.to_string()),
        }
    }
}

/// The class a port failure puts its error in.
fn port_class(port: &PortError) -> ErrorClass {
    match port {
        PortError::NotFound(_) => ErrorClass::NotFound,
        PortError::AccessDenied(_) => ErrorClass::AccessDenied,
        PortError::Unsupported(_) => ErrorClass::Unsupported,
        PortError::InvalidInput(_) => ErrorClass::InvalidInput,
        PortError::TimedOut(_) => ErrorClass::TimedOut,
        // `PortError` is non-exhaustive: a variant added later degrades to `Other`.
        _ => ErrorClass::Other,
    }
}

/// The error of a port, with the kind the UI switches on and `phrase` for the whole failure.
pub(crate) fn kinded(port: &PortError, phrase: &Phrase) -> IpcError {
    IpcError::coded(port_class(port), phrase)
}

/// The error of an execution failure: the kind of the port failure under it, `phrase` for all.
fn exec_error(exec: &ExecError, phrase: &Phrase) -> IpcError {
    match exec {
        ExecError::Detect(port)
        | ExecError::Journal(port)
        | ExecError::MarkApplied(port)
        | ExecError::Apply { error: port, .. } => kinded(port, phrase),
        // `ExecError` is non-exhaustive: anything new degrades to `Other`.
        _ => IpcError::other(phrase),
    }
}

/// "tweak `x`: <reason>".
fn tweak_failed(tweak: &str, reason: Phrase) -> Phrase {
    Phrase::new("err.tweak.failed")
        .text("tweak", tweak)
        .phrase("reason", reason)
}

impl From<TweakError> for IpcError {
    /// Keeps the kind of the underlying port failure when there is one, so the UI can tell
    /// "access denied" from "not found"; the sentence names the tweak and the class of the
    /// failure, never a port message.
    fn from(error: TweakError) -> Self {
        match &error {
            TweakError::UnknownTweak(tweak) => {
                Self::not_found(&Phrase::new("err.tweak.unknown").text("tweak", tweak))
            }
            TweakError::NothingToRevert(tweak) => {
                Self::not_found(&Phrase::new("err.tweak.nothingToRevert").text("tweak", tweak))
            }
            TweakError::NeedsAdministrator(tweak) => {
                Self::access_denied(&Phrase::new("err.tweak.needsAdmin").text("tweak", tweak))
            }
            TweakError::Detect {
                tweak, error: port, ..
            }
            | TweakError::Plan {
                tweak,
                error: PlanError::Detect { error: port, .. },
            } => kinded(
                port,
                &Phrase::new("err.tweak.detect")
                    .text("tweak", tweak)
                    .phrase("class", error_class_phrase(port)),
            ),
            TweakError::Journal {
                tweak, error: port, ..
            } => kinded(
                port,
                &Phrase::new("err.tweak.journal")
                    .text("tweak", tweak)
                    .phrase("class", error_class_phrase(port)),
            ),
            TweakError::Exec { tweak, error: exec } => {
                exec_error(exec, &tweak_failed(tweak, exec_phrase(exec)))
            }
            TweakError::Revert {
                tweak,
                error: revert,
            } => {
                let phrase = tweak_failed(tweak, revert_phrase(revert));
                match revert {
                    RevertError::Journal(port)
                    | RevertError::Port(port)
                    | RevertError::MarkReverted(port) => kinded(port, &phrase),
                    RevertError::EntryNotFound(_) => Self::not_found(&phrase),
                    RevertError::NotRevertible(_) => Self::invalid(&phrase),
                    // `RevertError` is non-exhaustive: anything new degrades to `Other`.
                    _ => Self::other(&phrase),
                }
            }
            TweakError::NothingToReset(tweak) => {
                Self::invalid(&Phrase::new("err.tweak.nothingToReset").text("tweak", tweak))
            }
            TweakError::AppliedByVolt(tweak) => {
                Self::invalid(&Phrase::new("err.tweak.appliedByVolt").text("tweak", tweak))
            }
            TweakError::NotDrifted(tweak) => {
                Self::invalid(&Phrase::new("err.tweak.notDrifted").text("tweak", tweak))
            }
            // Both enums are non-exhaustive: anything new degrades to `Other`.
            _ => Self::plain(ErrorClass::Other, error.to_string()),
        }
    }
}

impl From<StartupError> for IpcError {
    /// Machine-wide entries need administrator rights, which is `accessDenied` with a sentence
    /// the UI can show as it is; a failed change keeps the kind of the port failure under it.
    /// The sentences are built from the core's redacted reasons, not from port messages.
    fn from(error: StartupError) -> Self {
        match &error {
            StartupError::InvalidId(id) => {
                Self::invalid(&Phrase::new("err.startup.invalidId").text("id", id))
            }
            StartupError::NotFound(id) => {
                Self::not_found(&Phrase::new("err.startup.notFound").text("id", id))
            }
            StartupError::NeedsAdministrator { name } => {
                Self::access_denied(&Phrase::new("err.startup.needsAdmin").text("name", name))
            }
            StartupError::Protected { name, critical } => Self::access_denied(
                &Phrase::new(if *critical {
                    "err.startup.critical"
                } else {
                    "err.startup.protected"
                })
                .text("name", name),
            ),
            StartupError::Read(port) => kinded(
                port,
                &Phrase::new("err.startup.read").phrase("class", error_class_phrase(port)),
            ),
            StartupError::Change(exec) => exec_error(
                exec,
                &Phrase::new("err.startup.change").phrase("reason", exec_phrase(exec)),
            ),
            // `StartupError` is non-exhaustive: anything new degrades to `Other`.
            _ => Self::plain(ErrorClass::Other, error.to_string()),
        }
    }
}

impl From<StoreError> for IpcError {
    /// Opening the database failed. The UI can do nothing about the kind, so it is `Other`.
    fn from(error: StoreError) -> Self {
        Self::plain(ErrorClass::Other, error.to_string())
    }
}

