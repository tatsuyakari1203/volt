/// Writes the TypeScript bindings to `path`.
///
/// # Errors
/// Returns the exporter's error when a type cannot be represented in TypeScript (for example a
/// 64-bit integer) or the file cannot be written.
pub fn export_bindings(path: &Path) -> Result<(), specta_typescript::ExportError> {
    bindings_builder().export(Typescript::default().header(BINDINGS_HEADER), path)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn port_errors_map_to_the_matching_kind_and_keep_the_message() {
        let cases = [
            (
                PortError::NotFound("key".into()),
                IpcError::NotFound {
                    message: "key".into(),
                    phrase: None,
                },
            ),
            (
                PortError::AccessDenied("hklm".into()),
                IpcError::AccessDenied {
                    message: "hklm".into(),
                    phrase: None,
                },
            ),
            (
                PortError::Unsupported("linux".into()),
                IpcError::Unsupported {
                    message: "linux".into(),
                    phrase: None,
                },
            ),
            (
                PortError::InvalidInput("path".into()),
                IpcError::InvalidInput {
                    message: "path".into(),
                    phrase: None,
                },
            ),
            (
                PortError::TimedOut("slow".into()),
                IpcError::TimedOut {
                    message: "slow".into(),
                    phrase: None,
                },
            ),
            (
                PortError::Other("boom".into()),
                IpcError::Other {
                    message: "boom".into(),
                    phrase: None,
                },
            ),
        ];
        for (port, expected) in cases {
            let mapped = IpcError::from(port);
            assert_eq!(mapped, expected);
            assert_eq!(mapped.message(), expected.message());
        }
    }

    #[test]
    fn ipc_errors_serialize_as_a_value_tagged_by_kind() {
        let json = serde_json::to_value(IpcError::from(PortError::NotFound("run key".into())))
            .unwrap_or_default();
        assert_eq!(
            json,
            serde_json::json!({ "kind": "notFound", "message": "run key" })
        );
        let coded = serde_json::to_value(IpcError::invalid(&Phrase::new("err.scanRunning")))
            .unwrap_or_default();
        assert_eq!(coded["kind"], "invalidInput");
        assert_eq!(coded["message"], "a scan is already running");
        assert_eq!(coded["phrase"]["code"], "err.scanRunning");
    }

    #[test]
    fn tweak_errors_keep_the_kind_of_the_port_failure_under_them() {
        let detect = TweakError::Detect {
            tweak: "x".into(),
            step: 0,
            error: PortError::AccessDenied("hklm".into()),
        };
        let mapped = IpcError::from(detect);
        assert_eq!(mapped.class(), ErrorClass::AccessDenied);
        assert!(mapped.message().contains("tweak `x`"));
        assert!(!mapped.message().contains("hklm"));
        assert_eq!(
            mapped.phrase().map(|phrase| phrase.code.as_str()),
            Some("err.tweak.detect")
        );
        let exec = TweakError::Exec {
            tweak: "x".into(),
            error: ExecError::Journal(PortError::Other("disk full".into())),
        };
        assert_eq!(IpcError::from(exec).class(), ErrorClass::Other);
        let unreadable = TweakError::Plan {
            tweak: "x".into(),
            error: PlanError::Detect {
                index: 0,
                error: PortError::Unsupported("commands".into()),
            },
        };
        assert_eq!(IpcError::from(unreadable).class(), ErrorClass::Unsupported);
    }

    #[test]
    fn unknown_tweaks_and_nothing_to_revert_are_not_found() {
        assert_eq!(
            IpcError::from(TweakError::UnknownTweak("nope".into())).class(),
            ErrorClass::NotFound
        );
        assert_eq!(
            IpcError::from(TweakError::NothingToRevert("x".into())).class(),
            ErrorClass::NotFound
        );
    }

    #[test]
    fn a_tweak_that_needs_administrator_rights_is_access_denied() {
        assert_eq!(
            IpcError::from(TweakError::NeedsAdministrator("x".into())).class(),
            ErrorClass::AccessDenied
        );
    }

    #[test]
    fn revert_errors_map_by_what_went_wrong() {
        let revert = |error| {
            IpcError::from(TweakError::Revert {
                tweak: "x".into(),
                error,
            })
            .class()
        };
        assert_eq!(
            revert(RevertError::Port(PortError::AccessDenied("k".into()))),
            ErrorClass::AccessDenied
        );
        assert_eq!(
            revert(RevertError::EntryNotFound(volt_core::EntryId(3))),
            ErrorClass::NotFound
        );
        assert_eq!(
            revert(RevertError::NotRevertible(volt_core::EntryState::Reverted)),
            ErrorClass::InvalidInput
        );
    }

    #[test]
    fn startup_errors_keep_their_kind_and_say_administrator_rights_in_words() {
        let admin = IpcError::from(StartupError::NeedsAdministrator {
            name: "Vendor Updater".into(),
        });
        assert_eq!(admin.class(), ErrorClass::AccessDenied);
        assert_eq!(
            admin.message(),
            "Changing \"Vendor Updater\" needs administrator rights."
        );
        assert_eq!(
            admin.phrase().map(|phrase| phrase.code.as_str()),
            Some("err.startup.needsAdmin")
        );
        for (critical, code) in [
            (false, "err.startup.protected"),
            (true, "err.startup.critical"),
        ] {
            let protected = IpcError::from(StartupError::Protected {
                name: "Cloud".into(),
                critical,
            });
            assert_eq!(protected.class(), ErrorClass::AccessDenied);
            assert_eq!(
                protected.phrase().map(|phrase| phrase.code.as_str()),
                Some(code)
            );
        }
        assert_eq!(
            IpcError::from(StartupError::NotFound("x".into())).class(),
            ErrorClass::NotFound
        );
        assert_eq!(
            IpcError::from(StartupError::InvalidId("x".into())).class(),
            ErrorClass::InvalidInput
        );
        // A failed change keeps the kind of the port failure and never carries its message.
        let failed = IpcError::from(StartupError::Change(ExecError::Apply {
            error: PortError::AccessDenied("secret detail".into()),
            journal: None,
        }));
        assert_eq!(failed.class(), ErrorClass::AccessDenied);
        assert!(!failed.message().contains("secret"));
        let unreadable =
            IpcError::from(StartupError::Read(PortError::Other("secret detail".into())));
        assert_eq!(unreadable.class(), ErrorClass::Other);
        assert!(!unreadable.message().contains("secret"));
    }

    #[test]
    fn store_errors_reach_the_ui_as_other_with_their_message() {
        let error = StoreError::SchemaTooNew {
            found: 9,
            supported: 3,
        };
        let text = error.to_string();
        assert_eq!(
            IpcError::from(error),
            IpcError::Other {
                message: text,
                phrase: None
            }
        );
    }
}
